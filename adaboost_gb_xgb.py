from sklearn.datasets import load_iris
from  sklearn.model_selection import train_test_split
from sklearn.ensemble import AdaBoostClassifier , GradientBoostingClassifier
from xgboost import XGBClassifier
from sklearn.metrics import accuracy_score , f1_score , precision_score , recall_score

data = load_iris()
x = data.data
y = data.target

x_train,x_test,y_train,y_test = train_test_split(x,y,test_size=0.2,random_state=42)

models = {
    "AdaBoost" : AdaBoostClassifier(random_state=42,n_estimators=50),
    "Gradient Bossting" : GradientBoostingClassifier(random_state=42),
    "XGBoosting" : XGBClassifier(random_state=42,n_estimators=50,eval_metric = "mlogloss")
}

for name,model in models.items():
  model.fit(x_train,y_train)
  y_pred = model.predict(x_test)

  print("Model:",name)
  print("Accuracy:",accuracy_score(y_test,y_pred))
  print("precision score", precision_score(y_test,y_pred,average="weighted",zero_division=0))
  print("recall score", recall_score(y_test,y_pred,average="weighted",zero_division=0))
  print("f1 score", f1_score(y_test,y_pred,average="weighted",zero_division=0))

